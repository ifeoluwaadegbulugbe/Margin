'use client';
import type { Source } from '@/stores/aiStatus';
import { cx } from '@/components/ui';

const LABEL: Record<Source | 'AUTHORED', string> = {
  ON_DEVICE: 'On-device',
  IN_CLOUD: 'Cloud',
  'IN_CLOUD (by mode)': 'Cloud',
  SCRIPTED: 'Offline script',
  AUTHORED: 'Written note',
};
const DOT: Record<Source | 'AUTHORED', string> = {
  ON_DEVICE: 'bg-mint', IN_CLOUD: 'bg-sky', 'IN_CLOUD (by mode)': 'bg-sky', SCRIPTED: 'bg-muted', AUTHORED: 'bg-sunshine',
};

/** The real inference source as reported by the SDK (or an honest label for written lines). */
export function SourceChip({ source, latencyMs, onClick, className }: { source: Source | 'AUTHORED' | null; latencyMs?: number | null; onClick?: () => void; className?: string }) {
  if (!source) return null;
  const tip = source === 'SCRIPTED'
    ? 'Offline script: the AI reply was unavailable or failed validation, so a written line from the course was shown.'
    : source === 'AUTHORED' ? 'Written by the course, not generated by AI.'
      : `Reported by Firebase AI Logic: inferenceSource = ${source}${latencyMs ? ` · ${latencyMs} ms` : ''}`;
  const Tag = onClick ? 'button' : 'span';
  return (
    <Tag onClick={onClick} title={tip} className={cx('inline-flex items-center gap-1.5 rounded-[8px] border border-line bg-white px-2 py-0.5 text-xs font-semibold text-ink-2', onClick && 'hover:border-violet/50', className)}>
      <span className={cx('h-2 w-2 rounded-full', DOT[source])} aria-hidden />
      {LABEL[source]}
      {latencyMs != null && source !== 'AUTHORED' && source !== 'SCRIPTED' && <span className="tabular text-muted">· {(latencyMs / 1000).toFixed(1)} s</span>}
    </Tag>
  );
}
